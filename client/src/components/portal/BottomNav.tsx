export default function BottomNav() {
  const location = useLocation()
  const { roleAtivo, setRoleAtivo, papeisDisponiveis } = usePortal()

  const rotas = ROTAS_POR_PAPEL[roleAtivo] ?? []

  return (
    <div className="flex items-center border-t border-slate-800 bg-slate-900 lg:hidden">
      {papeisDisponiveis.length > 1 && (
        <div className="flex border-r border-slate-800">
          {papeisDisponiveis.map((papel) => (
            <button
              key={papel}
              onClick={() => setRoleAtivo(papel)}
              className={`px-3 py-3 text-xs font-semibold transition-colors ${
                papel === roleAtivo
                  ? 'text-[#00FF88]'
                  : 'text-slate-500'
              }`}
            >
              {papel === 'CLIENT' && 'Cli'}
              {papel === 'ORGANIZER' && 'Org'}
              {papel === 'PORTARIA' && 'Port'}
            </button>
          ))}
        </div>
      )}

      <div className="flex flex-1 justify-around">
        {rotas.map((rota) => {
          const isActive =
            rota.path === '/portal/cliente'
              ? location.pathname === rota.path
              : location.pathname.startsWith(rota.path)

          return (
            <Link
              key={rota.path}
              to={rota.path}
              className={`flex min-h-[48px] min-w-[48px] flex-col items-center justify-center gap-0.5 px-2 py-2 transition-colors ${
                isActive ? 'text-[#00FF88]' : 'text-slate-500'
              }`}
            >
              {rota.icon}
              <span className="text-[10px] font-medium">{rota.label}</span>
            </Link>
          )
        })}
      </div>
    </div>
  )
}
